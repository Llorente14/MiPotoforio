// Keep only the slices of Shippori Mincho that the decorative Japanese text actually uses:
//   src/**/* (CJK characters) + @fontsource/shippori-mincho/500.css
//   -> public/fonts/jp/*.woff2 (each slice cut down to the used glyphs) and src/styles/jp-font.css
// The full Fontsource stylesheet is ~130 KiB of unicode-range rules and blocks the first paint.
// Runs before every build:  node scripts/jp-font.mjs
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = resolve(root, 'node_modules/@fontsource/shippori-mincho');
const outDir = resolve(root, 'public/fonts/jp');
const cssOut = resolve(root, 'src/styles/jp-font.css');

// Kana, CJK punctuation, ideographs and full-width forms.
const isJp = (cp) => (cp >= 0x3000 && cp <= 0x30ff) || (cp >= 0x3400 && cp <= 0x9fff) || (cp >= 0xff00 && cp <= 0xffef);
const sources = new Set(['.astro', '.tsx', '.ts', '.mdx', '.md', '.json']);

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path)));
    else if (sources.has(extname(entry.name))) files.push(path);
  }
  return files;
}

const used = new Set();
for (const file of await walk(resolve(root, 'src'))) {
  for (const ch of await readFile(file, 'utf8')) {
    const cp = ch.codePointAt(0);
    if (isJp(cp)) used.add(cp);
  }
}

const parseRange = (range) =>
  range.split(',').map((token) => {
    const [from, to = from] = token.trim().replace(/^U\+/i, '').split('-');
    return [parseInt(from, 16), parseInt(to, 16)];
  });

const hex = (cp) => `U+${cp.toString(16)}`;
const css = await readFile(resolve(pkg, '500.css'), 'utf8');
const rules = [];
const covered = new Set();
for (const block of css.matchAll(/url\(\.\/files\/([^)]+\.woff2)\)[\s\S]*?unicode-range:\s*([^;]+);/g)) {
  const [, file, range] = block;
  const spans = parseRange(range);
  const chars = [...used].filter((cp) => !covered.has(cp) && spans.some(([a, b]) => cp >= a && cp <= b)).sort((a, b) => a - b);
  if (chars.length === 0) continue;
  chars.forEach((cp) => covered.add(cp));
  rules.push({ file, chars });
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
for (const { file, chars } of rules) {
  const slice = await readFile(resolve(pkg, 'files', file));
  const text = String.fromCodePoint(...chars);
  await writeFile(resolve(outDir, file), await subsetFont(slice, text, { targetFormat: 'woff2' }));
}

const faces = rules.map(
  ({ file, chars }) => `@font-face {
  font-family: 'Shippori Mincho';
  font-style: normal;
  font-display: swap;
  font-weight: 500;
  src: url(/fonts/jp/${file}) format('woff2');
  unicode-range: ${chars.map(hex).join(',')};
}`,
);
await writeFile(
  cssOut,
  `/* Generated by scripts/jp-font.mjs: only the Shippori Mincho slices the decorative Japanese text uses. */\n${faces.join('\n\n')}\n`,
);

const missing = [...used].filter((cp) => !covered.has(cp));
console.log(`jp-font: ${used.size} characters in ${rules.length} slices${missing.length ? `, not in the font: ${missing.map((cp) => String.fromCodePoint(cp)).join('')}` : ''}`);
